export type Key = keyof (typeof DICT)['pt'];

@Injectable({ providedIn: 'root' })
export class I18n {
  readonly lang = signal<Lang>(
    (localStorage.getItem('lang') as Lang) ?? (navigator.language.startsWith('pt') ? 'pt' : 'en'),
  );
  readonly dict = computed(() => DICT[this.lang()]);

  t(key: Key): string {
    return this.dict()[key];
  }

  toggle() {
    const next: Lang = this.lang() === 'pt' ? 'en' : 'pt';
    this.lang.set(next);
    localStorage.setItem('lang', next);
    document.documentElement.lang = next === 'pt' ? 'pt-BR' : 'en';
  }
}
